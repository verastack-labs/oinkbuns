export interface AudioAsset {
  key: SfxId | MusicId;
  urls: string[];
}

// Every sound and music key with its candidate files, first choice first.
// AUDIO_FILES is generated by oinkbuns-internal/tools/sfx/export.mjs, so a
// key that lacks a file fails typecheck instead of failing at runtime.
export const AUDIO: AudioAsset[] = (Object.keys(AUDIO_FILES) as Array<SfxId | MusicId>).map((key) => ({
  key,
  urls: AUDIO_FILES[key].map((file) => `assets/audio/${file}`),
}));
